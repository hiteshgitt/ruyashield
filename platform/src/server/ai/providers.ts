import { parseBundle, type ChatMessage } from "./prompts";

// Model providers (blueprint §7). Exactly one is active, chosen by RUYA_AI_PROVIDER:
//   disabled (default) — no provider; AI requests return 503 ai_unavailable.
//   fixture            — deterministic offline stand-in for development, tests and eval. It is NOT a language model
//                        and says so in every summary.
//   openai             — any OpenAI-compatible chat-completions endpoint (OPENAI_BASE_URL, OPENAI_API_KEY, OPENAI_MODEL).
// Providers receive only the redacted bundle; no tools/functions are ever offered to the model.

export interface CompletionRequest { messages: ChatMessage[]; maxTokens: number; signal?: AbortSignal }
export interface Completion { text: string; tokensIn: number; tokensOut: number }
export interface AiProvider { name: string; model: string; complete(r: CompletionRequest): Promise<Completion> }

export class ProviderError extends Error {
  constructor(public code: "timeout" | "http" | "circuit_open" | "bad_response" | "network", message: string) { super(message); }
}

const estimate = (s: string) => Math.ceil(s.length / 4);

// ---------- fixture ----------

export const FIXTURE_MODEL = "fixture-deterministic/1";
export const FIXTURE_NOTE = "Generated by the offline fixture provider, not a language model.";

export const fixtureProvider: AiProvider = {
  name: "fixture",
  model: FIXTURE_MODEL,
  async complete({ messages }) {
    const user = messages.find((m) => m.role === "user")?.content ?? "";
    const b = parseBundle(user);
    const remediation = /Propose remediation/.test(user);
    // Chat: the fixture never echoes the question (it is untrusted); it answers from the finding material only.
    const chat = !!b?.conversation;
    let out: unknown;
    if (!b || !b.evidence.length) {
      out = {
        status: "inconclusive", summary: `${FIXTURE_NOTE} No captured evidence was available for this finding.`,
        uncertainty: "Without evidence nothing about the finding can be confirmed.",
        missing_evidence: ["A captured response for the affected location."], claims: [],
      };
    } else {
      const e = b.evidence[0];
      const check = b.checks.find((c) => c.retestSupported) ?? b.checks[0];
      const claims: unknown[] = [
        { type: "observation", text: `Evidence ${e.label} (${e.contentType}) was captured for “${b.finding.title}” at ${b.finding.location}.`, evidence_refs: [e.label], confidence: "confirmed" },
        { type: "inference", text: `The issue probably applies to other responses served by the same configuration; only ${b.finding.location} was observed.`, evidence_refs: [e.label], confidence: "likely" },
      ];
      if (remediation && check) {
        const steps = (b.finding.remediation ?? "").split(/(?<=[.!?])\s+|\n+/).map((s) => s.trim()).filter(Boolean);
        claims.push({
          type: "recommendation", text: `Apply the documented remediation, then request a RuyaShield re-test with ${check.id}.`,
          evidence_refs: [e.label], confidence: "likely", verification_check_ids: [check.id],
          steps: steps.length ? steps : ["Change the affected configuration as described in the finding."], approval_required: true,
        });
      }
      out = {
        status: "ok", summary: chat
          ? `${FIXTURE_NOTE} In reply to your question: the finding “${b.finding.title}” (${b.finding.severity}) is backed by evidence ${e.label}; ${check ? `${check.id} can re-test it after a change.` : "no re-test check is listed."}`
          : `${FIXTURE_NOTE} It restates the finding and its first evidence item.`,
        uncertainty: "Only the supplied evidence was considered; behaviour elsewhere on the asset is unknown.",
        missing_evidence: [], claims,
      };
    }
    const text = JSON.stringify(out);
    return { text, tokensIn: estimate(messages.map((m) => m.content).join("")), tokensOut: estimate(text) };
  },
};

// ---------- OpenAI-compatible ----------

export function openAiProvider(env: NodeJS.ProcessEnv = process.env, fetchImpl: typeof fetch = fetch): AiProvider | null {
  const key = env.OPENAI_API_KEY;
  const model = env.OPENAI_MODEL;
  if (!key || !model) return null;
  const base = (env.OPENAI_BASE_URL || "https://api.openai.com/v1").replace(/\/+$/, "");
  return {
    name: "openai",
    model,
    async complete({ messages, maxTokens, signal }) {
      let r: Response;
      try {
        r = await fetchImpl(`${base}/chat/completions`, {
          method: "POST", signal, redirect: "error",
          headers: { "content-type": "application/json", authorization: `Bearer ${key}` },
          body: JSON.stringify({ model, messages, temperature: 0, max_tokens: maxTokens, response_format: { type: "json_object" } }),
        });
      } catch (e) {
        if ((e as Error).name === "AbortError" || (e as Error).name === "TimeoutError") throw new ProviderError("timeout", "Provider timed out.");
        throw new ProviderError("network", "Provider could not be reached.");
      }
      if (!r.ok) throw new ProviderError("http", `Provider returned HTTP ${r.status}.`);
      const j = (await r.json().catch(() => null)) as { choices?: { message?: { content?: string } }[]; usage?: { prompt_tokens?: number; completion_tokens?: number } } | null;
      const text = j?.choices?.[0]?.message?.content;
      if (typeof text !== "string") throw new ProviderError("bad_response", "Provider reply had no content.");
      return { text, tokensIn: j?.usage?.prompt_tokens ?? 0, tokensOut: j?.usage?.completion_tokens ?? estimate(text) };
    },
  };
}

// ---------- resilience: timeout, one retry, circuit breaker ----------

export const TIMEOUT_MS = 30_000;
const BREAKER_FAILURES = 3;
const BREAKER_OPEN_MS = 60_000;
const breaker = new Map<string, { failures: number; openUntil: number }>();
export const resetBreaker = () => breaker.clear();

/** Calls the provider with a timeout and one retry. Opens a per-provider circuit after repeated failures. */
export async function callProvider(p: AiProvider, req: Omit<CompletionRequest, "signal">, now = Date.now): Promise<Completion> {
  const k = `${p.name}:${p.model}`;
  const s = breaker.get(k) ?? { failures: 0, openUntil: 0 };
  if (s.openUntil > now()) throw new ProviderError("circuit_open", "Provider temporarily disabled after repeated failures.");
  let last: unknown;
  for (let attempt = 0; attempt < 2; attempt++) {
    try {
      const out = await p.complete({ ...req, signal: AbortSignal.timeout(TIMEOUT_MS) });
      breaker.set(k, { failures: 0, openUntil: 0 });
      return out;
    } catch (e) {
      last = e;
      if (e instanceof ProviderError && e.code === "bad_response") break;
    }
  }
  s.failures++;
  if (s.failures >= BREAKER_FAILURES) { s.openUntil = now() + BREAKER_OPEN_MS; s.failures = 0; }
  breaker.set(k, s);
  throw last instanceof ProviderError ? last : new ProviderError("network", "Provider call failed.");
}

export function getProvider(env: NodeJS.ProcessEnv = process.env): AiProvider | null {
  switch ((env.RUYA_AI_PROVIDER ?? "disabled").toLowerCase()) {
    case "fixture": return fixtureProvider;
    case "openai": return openAiProvider(env);
    default: return null;
  }
}
